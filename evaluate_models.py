"""Reproducible evaluation of the pre-match win-probability models (no Streamlit needed).
Run:  python evaluate_models.py        ->  writes docs/model_evaluation.md and docs/model_metrics.csv

Honest design:
  * decisive matches only (Won/Lost); draws, ties and no-results are excluded
  * every feature is computed from matches BEFORE the one being predicted (no look-ahead)
  * two tests: (A) one time-ordered split (train on the first ~75% of matches, test on the last ~25%),
               (B) an expanding-window backtest: for each year Y >= 2021 train on years < Y, test on year Y
  * baseline = always predict the training win rate (what you get with no model at all)
"""
from collections import defaultdict
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.ensemble import GradientBoostingClassifier
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score, brier_score_loss, log_loss, roc_auc_score
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

ROOT = Path(__file__).parent
K, SHRINK = 24, 4


def build_features(m):
    m = m[m.result.isin(["Won", "Lost"])].sort_values("date").reset_index(drop=True)
    elo = defaultdict(lambda: 1500.0); h2h = defaultdict(lambda: [0, 0]); fmt_elo = defaultdict(lambda: 1500.0); recent = []
    rows = []
    for _, r in m.iterrows():
        pak, opp = fmt_elo[("Pakistan", r.format)], fmt_elo[(r.opponent, r.format)]
        w, n = h2h[(r.opponent, r.format)]
        rf = np.mean(recent[-8:]) if recent else 0.5
        rows.append(dict(elo_diff=pak - opp, elo_p=1 / (1 + 10 ** (-(pak - opp) / 400)), h2h=(w + SHRINK * 0.5) / (n + SHRINK),
                         h2h_n=n, form8=rf, home=float(r.location_type == "Home"), away=float(r.location_type == "Away"),
                         toss=float(bool(r.pak_won_toss)), bat_first=float(r.pak_batting_order == "Batting first"),
                         ko=float(bool(r.is_knockout)), is_test=float(r.format == "Test"), is_odi=float(r.format == "ODI"), y=int(r.is_win)))
        e = 1 / (1 + 10 ** (-(pak - opp) / 400)); fmt_elo[("Pakistan", r.format)] += K * (r.is_win - e); fmt_elo[(r.opponent, r.format)] -= K * (r.is_win - e)
        h2h[(r.opponent, r.format)] = [w + int(r.is_win), n + 1]; recent.append(int(r.is_win))
    return pd.concat([m[["date", "year", "format", "opponent"]], pd.DataFrame(rows)], axis=1)


FEATS = ["elo_diff", "h2h", "form8", "home", "away", "toss", "bat_first", "ko", "is_test", "is_odi"]


def score(y, p, name, n_train):
    p = np.clip(p, 1e-3, 1 - 1e-3)
    return dict(Model=name, Accuracy=accuracy_score(y, p >= .5), LogLoss=log_loss(y, p, labels=[0, 1]), Brier=brier_score_loss(y, p),
                AUC=roc_auc_score(y, p) if len(set(y)) > 1 else np.nan, N_test=len(y), N_train=n_train)


def fit_predict(tr, te):
    out = {"Baseline (training win rate)": np.full(len(te), tr.y.mean()), "Elo only": te.elo_p.values}
    lr = make_pipeline(StandardScaler(), LogisticRegression(C=0.5, max_iter=1000)).fit(tr[FEATS], tr.y); out["Logistic regression"] = lr.predict_proba(te[FEATS])[:, 1]
    gb = GradientBoostingClassifier(n_estimators=120, max_depth=2, learning_rate=0.05, subsample=0.8, random_state=0).fit(tr[FEATS], tr.y)
    out["Gradient boosting"] = gb.predict_proba(te[FEATS])[:, 1]
    return out


def main():
    m = pd.read_csv(ROOT / "data" / "pak_matches.csv", parse_dates=["date"]); d = build_features(m)
    cut = int(len(d) * .75); tr, te = d.iloc[:cut], d.iloc[cut:]
    A = pd.DataFrame([score(te.y, p, n, len(tr)) for n, p in fit_predict(tr, te).items()])
    ys, ps = [], defaultdict(list)
    for yr in range(2021, int(d.year.max()) + 1):
        a, t = d[d.year < yr], d[d.year == yr]
        if len(t) < 5 or len(a) < 60: continue
        ys.append(t.y.values)
        for n, p in fit_predict(a, t).items(): ps[n].append(p)
    y = np.concatenate(ys); B = pd.DataFrame([score(y, np.concatenate(v), n, np.nan) for n, v in ps.items()])
    A.insert(0, "Test", "A: time split"); B.insert(0, "Test", "B: yearly backtest"); pd.concat([A, B]).to_csv(ROOT / "docs" / "model_metrics.csv", index=False)
    f = lambda t: t.drop(columns="Test").assign(Accuracy=lambda x: (100 * x.Accuracy).round(1).astype(str) + "%", LogLoss=lambda x: x.LogLoss.round(3),
                                                  Brier=lambda x: x.Brier.round(3), AUC=lambda x: x.AUC.round(3), N_train=lambda x: x.N_train.map(lambda v: "-" if pd.isna(v) else int(v))).to_markdown(index=False)
    md = f"""# Model evaluation (pre-match win probability)

Generated by `evaluate_models.py` from `data/pak_matches.csv`. Re-run it to reproduce.

**Setup.** Decisive matches only ({len(d)} Tests/ODIs/T20Is with a Won/Lost result). Every feature uses only matches played *before* the one being predicted
(Elo rating gap per format, shrunk head-to-head record, last-8 form, home/away, toss, batting order, knockout flag, format).
The baseline always predicts Pakistan's win rate in the training data, which is what you get with no model.

## A. One time-ordered split
Train on the first {len(tr)} matches (up to {tr.date.max():%d %b %Y}); test on the last {len(te)} (from {te.date.min():%d %b %Y}).

{f(A)}

## B. Expanding-window backtest (2021 onward)
For each year Y, train on all earlier years and predict year Y ({len(y)} predictions in total). This uses far more test matches than split A, so it is the steadier number.

{f(B)}

## How to read this
* Lower LogLoss and Brier are better; AUC 0.5 is a coin flip.
* Accuracy on a few dozen matches moves by several points on one or two results, so compare models on LogLoss/Brier and look at the backtest, not only at split A.
* Compare A with B. If a model looks much better in A than in B, the gap is mostly luck from a small test set, and B is the number to trust.
* Toss and batting order are known only at the toss, so this is a *post-toss* prediction; the other features are known days ahead.
* If a model does not clearly beat the baseline here, the honest conclusion is that Pakistan's results are close to unpredictable from these pre-match facts. Toss and batting order carry almost no signal.
"""
    (ROOT / "docs" / "model_evaluation.md").write_text(md); print(md)


if __name__ == "__main__":
    main()
